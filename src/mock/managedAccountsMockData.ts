// Risk levels derived from Risk Management aggregation logic:
// locked → critical, tier:critical → high, tier:standard or inactive → medium, otherwise low
function deriveRisk(tags: string[], status: ManagedAccount['status']): ManagedAccountRiskLevel {
  if (status === 'locked' || status === 'marked_for_deletion' || status === 'deleted') return 'critical';
  const tagStr = tags.join(' ').toUpperCase();
  if (tagStr.includes('TIER:CRITICAL') || tagStr.includes('SENSITIVE')) return 'high';
  if (status === 'inactive' || status === 'pending') return 'medium';
  if (tagStr.includes('ENV:PROD')) return 'medium';
  return 'low';
}

